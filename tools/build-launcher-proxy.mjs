// Builds the desktop launcher's steam_api proxy (launcher/proxy, DESKTOP-LAUNCHER-PLAN.md "The proxy") with MSVC x86.
//   node tools/build-launcher-proxy.mjs            build/launcher/proxy/steam_api.dll
//   node tools/build-launcher-proxy.mjs --test     also build fake_upstream + proxy_test into build/launcher/proxy-test
//                                                  and run it (exit code = the test's)
//   node tools/build-launcher-proxy.mjs --write-forwards <steam_api.dll>   regenerate launcher/proxy/forwards.h from a
//                                                  stock steam_api.dll's export table (read as bytes, never loaded)
// Needs Visual Studio Build Tools with the C++ x86 compiler (found with vswhere). Our own code only: the original
// game files are never loaded or run.
import {spawnSync} from 'node:child_process';
import {existsSync,mkdirSync,copyFileSync,readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readPe} from './pe-imports.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const src=path.join(root,'launcher/proxy');
const args=process.argv.slice(2);

// One linker directive per forwarded export (an x86 .def file would not take forwarders here), included by
// steam_api_proxy.c. SteamUser and SteamFriends are the proxy's own __declspec(dllexport) functions.
export function forwardsHeader(steamApiBytes){
 const names=readPe(steamApiBytes).exports.filter(n=>n!=='SteamUser'&&n!=='SteamFriends');
 return ['/* steam_api proxy forwarders (generated by tools/build-launcher-proxy.mjs --write-forwards from the stock client',
  ` steam_api.dll, sha256 45b2de34...6d688, LumaEmu: ${names.length+2} exports). Every one forwards to the player's own DLL`,
  '   except SteamUser and SteamFriends, which steam_api_proxy.c implements. librust.dll imports 20 of them. */',
  ...names.map(n=>`#pragma comment(linker, "/EXPORT:${n}=steam_api_upstream.${n}${n.startsWith('g_')?',DATA':''}")`),''].join('\n');
}

function vcvars(){
 const vswhere=path.join(process.env['ProgramFiles(x86)']??'C:\\Program Files (x86)','Microsoft Visual Studio/Installer/vswhere.exe');
 if(!existsSync(vswhere))throw new Error('vswhere.exe not found: install Visual Studio Build Tools with C++.');
 const r=spawnSync(vswhere,['-latest','-products','*','-requires','Microsoft.VisualStudio.Component.VC.Tools.x86.x64','-property','installationPath'],{encoding:'utf8'});
 const install=r.stdout.trim().split(/\r?\n/)[0];
 const bat=install&&path.join(install,'VC/Auxiliary/Build/vcvarsall.bat');
 if(!bat||!existsSync(bat))throw new Error('No Visual Studio install with the C++ x86 tools.');
 return bat;
}

function cl(bat,cwd,commands){
 const script=path.join(cwd,'build.cmd');
 writeFileSync(script,['@echo off',`call "${bat}" x86 >nul || exit /b 1`,...commands.map(c=>c+' || exit /b 1')].join('\r\n')+'\r\n');
 const r=spawnSync('cmd.exe',['/d','/c',script],{cwd,encoding:'utf8'});
 if(r.status!==0){process.stdout.write(r.stdout??'');process.stderr.write(r.stderr??'');throw new Error('MSVC build failed.');}
}

const flags='/nologo /W4 /WX /O2 /MT /GS /guard:cf';
export function buildProxy(bat=vcvars()){
 const out=path.join(root,'build/launcher/proxy');mkdirSync(out,{recursive:true});
 cl(bat,out,[`cl ${flags} /LD "${path.join(src,'steam_api_proxy.c')}" /Fe:steam_api.dll /link /DYNAMICBASE /NXCOMPAT /SAFESEH advapi32.lib`]);
 return path.join(out,'steam_api.dll');
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 if(args[0]==='--write-forwards'){
  writeFileSync(path.join(src,'forwards.h'),forwardsHeader(readFileSync(args[1])));
  console.log('Wrote launcher/proxy/forwards.h');process.exit(0);
 }
 const bat=vcvars();
 const dll=buildProxy(bat);
 const pe=readPe(readFileSync(dll));
 if(pe.machine!==0x14c)throw new Error('proxy is not x86');
 console.log(`Built ${path.relative(root,dll)} (x86, ${pe.exports.length} exports)`);
 if(args.includes('--test')){
  const t=path.join(root,'build/launcher/proxy-test');mkdirSync(t,{recursive:true});
  copyFileSync(dll,path.join(t,'steam_api.dll'));
  cl(bat,t,[
   `cl ${flags.replace('/WX','')} /LD "${path.join(src,'test/fake_upstream.c')}" /Fe:steam_api_upstream.dll`,
   `cl ${flags.replace('/WX','')} "${path.join(src,'test/proxy_test.c')}" /Fe:proxy_test.exe`,
   `cl ${flags.replace('/WX','')} "${path.join(src,'test/proxy_client.c')}" /Fe:proxy_client.exe`]);
  const r=spawnSync(path.join(t,'proxy_test.exe'),[],{cwd:t,encoding:'utf8',timeout:60000});
  process.stdout.write(r.stdout??'');process.stderr.write(r.stderr??'');
  process.exit(r.status??1);
 }
}
