// The client's own GPU grass (FPGrass, grass.on), ported from the decompiled FPGrass*.cs / grass.cs and the shipped
// Custom/FPGrassShader + Custom/RenderSplatProbability programs (analysis/grass-source/shaders, the "opengl" GLSL
// subprogram and the d3d9 ps_3_0 probability program). Data comes from tools/export_grass.py.
//
// What the original does, and what this module reproduces:
//  - FPGrass has 2 FPGrassLevels (spacing 0.368 m / 0.735 m, 125 m / 250 m wide). Each level is 4x4 FPGrassPatches of
//    85x85 blades (one quad per blade; all 4 corners start on the blade's grid point). A level's centre is the camera
//    position snapped down to the level spacing; patches draw at centre + patch offset, each culled by the camera
//    frustum against a box from 4 terrain corner heights +-5 m (FPGrassPatch.Render). Nothing else is culled: the
//    finer level is drawn under the coarser one near the camera.
//  - When a level's centre moves, RenderSplatProbability redraws that level's 512x512 probability texture: per grid
//    cell a noise value picks a terrain splat channel by cumulative weight, then one of that channel's 4 detail slots
//    by cumulative probability (FPGrassProbabilities 16x2 table); R = (detail id + 1)/256, 0 for no grass.
//  - The vertex program reads the cell's detail id, snaps the blade to the level grid in terrain space, scatters it by
//    noise2, puts it on the terrain triangle (heights), sizes it from FPGrassProperty (min/max width/height lerped by
//    noise), leans it between the ground normal and a noise "up" by _GroundNormalBias, fades its height by
//    (1 - (dx^4 + dz^4)/_Distance^4)^2, sways the top with Unity's terrain-grass wave and tints it with _WavingTint.
//    Lighting uses the terrain normal map normal (Lambert, Unity "PrePass" passes); alpha test 0.5, no culling.
//  - The passes carry REQUIREOPTIONS=SoftVegetation: QualitySettings Fastest/Fast/Simple have softVegetation off, so the
//    original draws no grass at those Render Quality levels; Good/Beautiful/Fantastic draw it.
//  - grass.displacement: the displacement camera renders layer GrassDisplacement into a 512 RT that is blitted into the
//    probability texture's G channel. No shipped prefab or scene object carries FPGrassDisplacementRadius/Trail, so
//    that channel stays 0 and displacement never shows; the shader path is kept (and disabled by the convar as original).
//  - grass.forceredraw regenerates the probability textures on every draw.
// Port approximations: heights come from the terrain heightmap texture (the original's encoded Height texture matches
// it within 0.042 m, see manifest.height); lighting follows browser/legacy-materials.mjs's
// gamma-space light pre-pass model with three's light uniforms instead of Unity's light buffer; the sun term takes the sun
// shadow (browser/sun-shadows.mjs) while grass.shadowreceive is on; atlas mipmaps are generated by WebGL instead of Unity's.
//  - Shadows: FPGrassLevel.Draw submits every visible patch with Graphics.DrawMesh(..., FPGrass.castShadows,
//    FPGrass.receiveShadows) - the grass.shadowcast (default false) / grass.shadowreceive (default true) convars.
//    Casting uses the shader's SHADOWCASTER pass (SHADOWS_DEPTH): the same blade vertex program, Cull Off, Offset 1, 1,
//    discard where the atlas alpha - 0.5 < 0. It only matters where the grass draws (Good+, SoftVegetation) and the level
//    has sun shadows (Good+). Port: each level's mesh gets that depth program as its customDepthMaterial and renders into
//    the sun cascades (browser/sun-shadows.mjs) for the patches the main camera kept (DrawMesh was per camera); the
//    blade fade/size uses the main camera position in the caster too (the program's _WorldSpaceCameraPos; assumed to be
//    the main camera's during Unity's shadow pass). Unity's caster bias (unity_LightShadowBias) is replaced by the port's
//    receiver-side bias as for every other caster.

