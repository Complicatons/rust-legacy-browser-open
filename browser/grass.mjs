// FPGrassLevel.UpdateLevel: Mathf.FloorToInt(position / gridSpacingAtLevel) * gridSpacingAtLevel (float32 values).
export function levelCentre(x,z,spacing){return [f32(Math.floor(f32(f32(x)/spacing))*spacing),f32(Math.floor(f32(f32(z)/spacing))*spacing)];}

// FPGrassProbabilityGenerator.UpdateMap: the quad's texture coordinates start at terrain-local
// position - FloorToInt(gridSize * 0.5 * gridScale) (the float argument rounds 62.4999988 / 124.9999976 to 62.5 / 125).
export function probabilityStart(centreX,centreZ,terrainPosition,gridSize,gridScale){
 const half=Math.floor(f32(gridSize*0.5*gridScale)),x=f32(centreX-terrainPosition[0]),z=f32(centreZ-terrainPosition[2]);
 return [f32(x-half),f32(z-half)];
}

// FPGrassProbabilities pixels -> the Alpha8 bytes the program reads (Unity converts floats to bytes with rounding).
export function detailTable(pixels){
 const ids=new Float32Array(16),probs=new Float32Array(16);
 for(let i=0;i<16;i++){ids[i]=Math.round(Math.min(1,Math.max(0,pixels[i][3]))*255)/255;probs[i]=Math.round(Math.min(1,Math.max(0,pixels[i+16][3]))*255)/255;}
 return {ids,probs};
}
// RenderSplatProbability pass 0 for one cell (JS mirror of the GLSL below): splat = RGBA weights 0..1, noise = filtered
// noise alpha. Returns the value written to R (0..1, before 8-bit storage).
export function probabilityValue(splat,noise,table){
 const r=Math.min(1,Math.max(0.00010002,noise));let cum=0,channel=0;
 for(let c=0;c<4;c++){cum+=splat[c];if(cum>=r){channel=c+1;break;}}
 const row=channel-1,at=k=>Math.max(0,Math.min(15,row*4+k));let p=0,slot=0;
 for(let k=0;k<4;k++){p+=table.probs[at(k)];if(p>=r){slot=k+1;break;}}
 return slot?table.ids[at(slot-1)]+1/256:0;
}
// FPGrassLayer.UpdateDisplacement camera centre (x, z): moves only when more than recentreDistance away in 2-D, then
// snaps to multiples of orthographicSize / texture width.
export function displacementCentre(current,x,z,{cameraOrthographicSize=50,renderTextureSize=512,recentreDistance=5}={}){
 if(current&&Math.hypot(x-current[0],z-current[1])<=recentreDistance)return current;
 const step=cameraOrthographicSize/renderTextureSize;return [Math.round(x/step)*step,Math.round(z/step)*step];
}
// What the grass vertex program decodes from a stored byte: floor(byte/255 * 256) - 1 (-1 = no grass).
export function decodeDetail(byte){return Math.floor(byte/255*256)-1;}
export function storeByte(value){return Math.round(Math.min(1,Math.max(0,value))*255);}

// FPGrassPatch.Render bounds: heights at the 4 patch corners, min - 5 .. max + 5 (Unity coordinates).
export function patchBounds(x,z,patchSize,sampleHeight){
 const h=patchSize*0.5,a=sampleHeight(x-h,z+h),b=sampleHeight(x-h,z-h),c=sampleHeight(x+h,z+h),d=sampleHeight(x+h,z-h);
 return {min:[x-h,Math.min(a,b,c,d)-5,z-h],max:[x+h,Math.max(a,b,c,d)+5,z+h]};
}
// Vertex program height fade: 1 - clamp((dx^4 + dz^4) / D^4), applied twice to the blade height.
export function distanceFade(dx,dz,distance){return 1-Math.min(1,Math.max(0,(dx**4+dz**4)/distance**4));}

// The shipped patch mesh, rebuilt (tools/export_grass.py verifies all 32 meshes against this layout): blade b at
// (-size/2 + floor(b/n)*spacing, 0, -size/2 + (b%n)*spacing), tangent = (corner x, corner y, cell x, cell z).
export function patchTemplate(n,spacing,patchSize){
 const blades=n*n,position=new Float32Array(blades*12),corner=new Float32Array(blades*8),cell=new Float32Array(blades*8),index=new Uint16Array(blades*6),half=patchSize/2;
 const cx=[-0.5,0.5,-0.5,0.5],cy=[0,0,1,1];
 for(let b=0;b<blades;b++){const bx=Math.floor(b/n),bz=b%n,x=f32(-half+bx*spacing),z=f32(-half+bz*spacing);
  for(let k=0;k<4;k++){const v=b*4+k;position[v*3]=x;position[v*3+2]=z;corner[v*2]=cx[k];corner[v*2+1]=cy[k];cell[v*2]=bx;cell[v*2+1]=bz;}
  index.set([b*4,b*4+2,b*4+3,b*4,b*4+3,b*4+1],b*6);}
 return {position,corner,cell,index};
}

