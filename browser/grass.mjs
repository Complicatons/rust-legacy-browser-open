function bitmapTexture(url,{color=false,filter='bilinear',wrap='clamp',mipmaps=false}={}){
 return new THREE.ImageBitmapLoader().setOptions({imageOrientation:'none',premultiplyAlpha:'none',colorSpaceConversion:'none'}).loadAsync(url).then(bitmap=>{
  const t=new THREE.Texture(bitmap);t.flipY=false;t.premultiplyAlpha=false;t.colorSpace=color?THREE.SRGBColorSpace:THREE.NoColorSpace;
  t.wrapS=t.wrapT=wrap==='repeat'?THREE.RepeatWrapping:THREE.ClampToEdgeWrapping;t.generateMipmaps=mipmaps;
  t.magFilter=filter==='point'?THREE.NearestFilter:THREE.LinearFilter;
  t.minFilter=filter==='point'?(mipmaps?THREE.NearestMipmapNearestFilter:THREE.NearestFilter):mipmaps?(filter==='trilinear'?THREE.LinearMipmapLinearFilter:THREE.LinearMipmapNearestFilter):THREE.LinearFilter;
  t.needsUpdate=true;return t;});
}

